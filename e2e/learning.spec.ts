import { test, expect } from '@playwright/test';
import { openExample } from './learning-helpers';
test('File example shelf describes experiments and opens a working feedback circuit', async ({ page }) => {
  await page.goto('/');
  await openExample(page, 'A heater that thinks');
  await expect(page.locator('.status-footer')).toContainText('8 connections');
  await expect(page.locator('[data-component="hysteresis"]')).toBeVisible();
  await expect(page.locator('.assembly-tools')).not.toContainText('Open');
});
test('mission starts empty, offers optional hints, and accepts equipment purchases', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: /Challenges/ }).click();
  await page.getByRole('button', { name: 'Start assignment' }).first().click();
  const guide = page.getByRole('dialog', { name: 'Challenge guidebook' });
  await expect(guide).toContainText('The lights are out');
  await expect(guide).toContainText('€0 / €100 spent');
  await expect(guide).toContainText('Full economy points at €68 or less');
  await expect(guide.getByText('A circuit needs a complete return path to its source.')).not.toBeVisible();
  await guide.getByText('Hint 1 · Find your approach').click();
  await expect(guide).toContainText('A circuit needs a complete return path');
  await page.getByRole('button', { name: 'Let’s build' }).click();
  await expect(page.locator('[data-component]')).toHaveCount(0);
  await page.locator('.library-component').filter({ has: page.getByText('DC power supply', { exact: true }) }).click();
  await expect(page.getByLabel('Voltage setpoint', { exact: true })).toHaveValue('12');
  await page.getByRole('button', { name: 'Open challenge guidebook' }).click();
  await expect(guide).toContainText('€45 / €100 spent');
});
test('example shelf fits a phone and filters mechanisms', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  await page.locator('.file-menu > summary').click();
  await page.getByRole('button', { name: 'Starters & examples', exact: true }).click();
  await page.getByRole('button', { name: 'Mechanisms', exact: true }).click();
  await expect(page.locator('.example-card')).toHaveCount(5);
  await expect(page.getByRole('button', { name: 'Open Gravity playground' })).toBeVisible();
  const bounds = await page.getByRole('dialog').boundingBox();
  expect(bounds!.width).toBeLessThanOrEqual(390);
});
test('descent mission lets the player buy and tune the brake, then land safely', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: /Challenges/ }).click();
  await page.getByRole('button', { name: 'Start assignment' }).nth(6).click();
  await expect(page.getByRole('dialog', { name: 'Challenge guidebook' })).toContainText('Four metres to fall');
  await page.getByRole('button', { name: 'Let’s build' }).click();
  await page.getByRole('button', { name: 'Schematic view', exact: true }).click();
  await expect(page.locator('[data-component="forceActuator"]')).toHaveCount(0);
  await page.locator('.library-component').filter({ has: page.getByText('Force / brake actuator', { exact: true }) }).click();
  await page.getByLabel('Brake damping', { exact: true }).fill('200');
  await page.getByLabel('Brake damping', { exact: true }).press('Enter');
  await page.getByRole('button', { name: 'Advance 60 s' }).click();
  await expect(page.locator('.challenge-strip')).toContainText('stars');
});
test('heat exchanger example opens from the water shelf and visibly recovers heat', async ({ page }) => {
  await page.goto('/');
  await page.locator('.file-menu > summary').click();
  await page.getByRole('button', { name: 'Starters & examples', exact: true }).click();
  await page.getByRole('button', { name: 'Water & industry', exact: true }).click();
  await page.getByRole('button', { name: 'Open Heat exchanger lab', exact: true }).click();
  await expect(page.locator('[data-component="heatExchanger"]')).toHaveCount(1);
  await expect(page.locator('[data-component="tank"]')).toHaveCount(4);
  await expect(page.locator('.status-footer')).toContainText('6 connections');
  await page.getByRole('button', { name: 'Advance 60 s' }).click();
  await expect(page.getByRole('button', { name: 'Advance 60 s' })).toBeEnabled({ timeout: 30000 });
  await expect(page.locator('.trace-readouts')).toContainText('Recovered heat');
  await page.locator('[data-component="heatExchanger"]').click();
  await expect(page.getByLabel('Heat-transfer conductance UA', { exact: true })).toHaveValue('5000');
  await expect(page.locator('.reading-caption')).toHaveText('Hot stream flow');
  await expect(page.locator('[data-component="heatExchanger"] .live-caption')).toContainText('kW heat');
});
